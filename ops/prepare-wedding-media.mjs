// Install only mapped owner-photo derivatives. Never overwrites originals or legacy art.
import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
const project = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const manifest = JSON.parse(
  await fs.readFile(
    path.join(project, "docs/design/jo-venta/asset-manifest.json"),
    "utf8",
  ),
);
const output = path.join(
  project,
  "apps/invitation-web/public/assets/photography",
);
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const allowed = new Set([
  "cover.webp",
  "venta.webp",
  "jo.webp",
  "pic-01.webp",
  "pic-02.webp",
  "pic-03.webp",
  "gallery-cats-thumb.webp",
]);
const prepared = [];
for (const asset of manifest.assets) {
  if (!allowed.has(asset.output)) throw new Error("Unexpected asset mapping");
  const source = path.resolve(project, asset.sourcePath);
  const derived = path.resolve(project, asset.derivative.path);
  if (
    !source.startsWith(path.join(project, "gambar-edit") + path.sep) ||
    !derived.startsWith(
      path.join(project, "docs/design/jo-venta/media") + path.sep,
    )
  )
    throw new Error("Unexpected source path");
  const original = await fs.readFile(source);
  const bytes = await fs.readFile(derived);
  if (
    digest(original) !== asset.source.sha256 ||
    digest(bytes) !== asset.derivative.sha256
  )
    throw new Error(
      "Media changed: regenerate and review the manifest before installation",
    );
  prepared.push({ filename: asset.output, bytes });
  if (asset.thumbnail) {
    const thumb = path.resolve(project, asset.thumbnail.path);
    if (
      path.basename(thumb) !== "gallery-cats-thumb.webp" ||
      !thumb.startsWith(
        path.join(project, "docs/design/jo-venta/media") + path.sep,
      )
    )
      throw new Error("Unexpected thumbnail path");
    const thumbBytes = await fs.readFile(thumb);
    if (digest(thumbBytes) !== asset.thumbnail.sha256)
      throw new Error("Thumbnail changed after review mapping");
    prepared.push({ filename: path.basename(thumb), bytes: thumbBytes });
  }
}
if (
  prepared.length !== allowed.size ||
  new Set(prepared.map((item) => item.filename)).size !== allowed.size
)
  throw new Error("Incomplete photo mapping");
await fs.mkdir(output, { recursive: true });
const versionedName = (item) =>
  `${path.parse(item.filename).name}-${digest(item.bytes).slice(0, 16)}.webp`;
for (const item of prepared)
  await fs.writeFile(path.join(output, versionedName(item)), item.bytes);
const keys = {
  "cover.webp": "cover",
  "venta.webp": "venta",
  "jo.webp": "jo",
  "pic-01.webp": "pic01",
  "pic-02.webp": "pic02",
  "pic-03.webp": "pic03",
  "gallery-cats-thumb.webp": "galleryCatsThumb",
};
const urls = Object.fromEntries(
  prepared.map((item) => [
    keys[item.filename],
    `/assets/photography/${versionedName(item)}`,
  ]),
);
const generatedPath = path.join(
  project,
  "apps/invitation-web/src/presentation/wedding-media.generated.ts",
);
const generatedSource = `// Generated by ops/prepare-wedding-media.mjs. Public asset digests invalidate image caches.\nexport const ownerPhotography = ${JSON.stringify(urls, null, 2)} as const;\n`;
await fs.writeFile(
  generatedPath,
  await prettier.format(generatedSource, {
    ...(await prettier.resolveConfig(generatedPath)),
    filepath: generatedPath,
  }),
);
console.log(
  `Installed ${prepared.length} mapped photography files; original photos and legacy art retained.`,
);
