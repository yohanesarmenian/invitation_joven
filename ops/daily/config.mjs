import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { randomBytes, randomUUID, createHash } from "node:crypto";
import { protectPrivatePath } from "./private-files.mjs";

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const apiRequire = createRequire(resolve(root, "apps/api/package.json"));
export const rootRequire = createRequire(resolve(root, "package.json"));
export const dailyDirectory = resolve(root, ".local-daily");
export const configPath = resolve(root, ".env.daily");
export const rootIdentity = createHash("sha256")
  .update(root.toLowerCase())
  .digest("hex")
  .slice(0, 12);
const fields = [
  "DAILY_PROFILE_ID",
  "DAILY_DATABASE_PASSWORD",
  "DAILY_OPERATOR_PASSWORD",
  "CREDENTIAL_SECRET",
  "DAILY_PG_PORT",
  "DAILY_PUBLIC_PORT",
  "DAILY_ADMIN_PORT",
  "DAILY_API_PORT",
  "DAILY_CONTROL_PORT",
];
const defaults = {
  DAILY_PG_PORT: 55433,
  DAILY_PUBLIC_PORT: 3200,
  DAILY_ADMIN_PORT: 3201,
  DAILY_API_PORT: 4200,
  DAILY_CONTROL_PORT: 4201,
};

export function parseDailyConfig(input) {
  if (
    !input ||
    typeof input !== "object" ||
    Object.keys(input).some((key) => !fields.includes(key))
  )
    throw Error("Daily configuration has unsupported fields.");
  if (
    !/^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/.test(
      input.DAILY_PROFILE_ID ?? "",
    )
  )
    throw Error("Daily profile identity is invalid.");
  for (const name of ["DAILY_DATABASE_PASSWORD", "DAILY_OPERATOR_PASSWORD"])
    if (!/^[a-f0-9]{64}$/.test(input[name] ?? ""))
      throw Error("Daily database secrets must be generated by local:init.");
  const secret = input.CREDENTIAL_SECRET;
  if (
    typeof secret !== "string" ||
    !/^[\w-]{43}$/.test(secret) ||
    Buffer.from(secret, "base64url").toString("base64url") !== secret ||
    Buffer.from(secret, "base64url").length !== 32
  )
    throw Error("Daily credential secret is invalid.");
  const ports = {};
  for (const key of Object.keys(defaults)) {
    const value = input[key];
    if (
      typeof value !== "string" ||
      !/^[1-9]\d{0,4}$/.test(value) ||
      Number(value) > 65535
    )
      throw Error("Daily ports must be explicit valid TCP ports.");
    ports[key] = Number(value);
  }
  if (new Set(Object.values(ports)).size !== Object.keys(ports).length)
    throw Error("Daily ports must be distinct.");
  const fingerprint = createHash("sha256")
    .update(fields.map((key) => `${key}=${input[key]}`).join("\n"))
    .digest("hex");
  const project = `invitation-daily-${rootIdentity}`;
  const database = "invitation_daily",
    role = "invitation_daily_app",
    operator = "invitation_daily_operator";
  const databaseUrl = new URL(
    `postgresql://${role}@127.0.0.1:${ports.DAILY_PG_PORT}/${database}?schema=public`,
  );
  databaseUrl.password = input.DAILY_DATABASE_PASSWORD;
  const operatorUrl = new URL(
    `postgresql://${operator}@127.0.0.1:${ports.DAILY_PG_PORT}/postgres`,
  );
  operatorUrl.password = input.DAILY_OPERATOR_PASSWORD;
  return {
    ...ports,
    profileId: input.DAILY_PROFILE_ID,
    secret,
    databasePassword: input.DAILY_DATABASE_PASSWORD,
    operatorPassword: input.DAILY_OPERATOR_PASSWORD,
    database,
    role,
    operator,
    project,
    fingerprint,
    databaseUrl: databaseUrl.toString(),
    operatorUrl: operatorUrl.toString(),
    publicOrigin: `http://localhost:${ports.DAILY_PUBLIC_PORT}`,
    adminOrigin: `http://localhost:${ports.DAILY_ADMIN_PORT}`,
    apiOrigin: `http://127.0.0.1:${ports.DAILY_API_PORT}`,
    marker: `invitation-daily-v1:${rootIdentity}:${input.DAILY_PROFILE_ID}:${createHash("sha256").update(secret).digest("hex")}`,
  };
}

export async function loadDailyConfig() {
  let source;
  try {
    source = await readFile(configPath, "utf8");
  } catch {
    throw Error(
      "Daily configuration missing. Run local:init first; working .env is never used as fallback.",
    );
  }
  if (Buffer.byteLength(source) > 8192)
    throw Error("Daily configuration exceeds its size limit.");
  return parseDailyConfigSource(source);
}

export function parseDailyConfigSource(source) {
  if (typeof source !== "string" || Buffer.byteLength(source) > 8192)
    throw Error("Daily configuration exceeds its size limit.");
  const assignments = [
    ...source.matchAll(/^\s*(?:export\s+)?([A-Z_]+)\s*=/gm),
  ].map((match) => match[1]);
  if (new Set(assignments).size !== assignments.length)
    throw Error("Daily configuration has duplicate assignments.");
  return parseDailyConfig(apiRequire("dotenv").parse(source));
}

export async function initializeConfig() {
  await mkdir(dailyDirectory, { recursive: true });
  await protectPrivatePath(dailyDirectory, true);
  const generated = {
    DAILY_PROFILE_ID: randomUUID(),
    DAILY_DATABASE_PASSWORD: randomBytes(32).toString("hex"),
    DAILY_OPERATOR_PASSWORD: randomBytes(32).toString("hex"),
    CREDENTIAL_SECRET: randomBytes(32).toString("base64url"),
    ...Object.fromEntries(
      Object.entries(defaults).map(([key, value]) => [key, String(value)]),
    ),
  };
  try {
    await writeFile(
      configPath,
      fields.map((key) => `${key}=${generated[key]}`).join("\n") + "\n",
      { flag: "wx", mode: 0o600 },
    );
  } catch (error) {
    if (error.code !== "EEXIST")
      throw Error("Unable to create private daily configuration.");
  }
  await protectPrivatePath(configPath);
  return loadDailyConfig();
}

export function dailyEnvironment(config, ambient = process.env) {
  return {
    ...ambient,
    NODE_ENV: "development",
    DATABASE_URL: config.databaseUrl,
    CREDENTIAL_SECRET: config.secret,
    ADMIN_ORIGIN: config.adminOrigin,
    PUBLIC_INVITATION_BASE_URL: config.publicOrigin,
    ADMIN_API_INTERNAL_BASE_URL: config.apiOrigin,
    INVITATION_API_BASE_URL: config.apiOrigin,
    PORT: String(config.DAILY_API_PORT),
    API_HOST: "127.0.0.1",
    NEXT_DIST_DIR: ".next-daily",
    TURBOPACK: "",
    IS_TURBOPACK_TEST: "",
    IS_WEBPACK_TEST: "",
    RAYON_NUM_THREADS: "2",
    INVITATION_DATABASE_TESTS: "0",
    INVITATION_WORKFLOW_TEST: "0",
    VENUE_CONTENT_PREVIEW: "0",
    INVITATION_MOCK_PRESENTATION: "",
    ADMIN_BOOTSTRAP_EMAIL: "",
    ADMIN_BOOTSTRAP_PASSWORD: "",
  };
}

export function redactDailyOutput(value, config) {
  let text = String(value);
  for (const secret of [
    config.databaseUrl,
    config.operatorUrl,
    config.secret,
    config.databasePassword,
    config.operatorPassword,
  ])
    text = text.replaceAll(secret, "[redacted]");
  return text;
}
